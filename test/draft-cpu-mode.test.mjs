import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const rooms=readFileSync('supabase/migrations/20261022130000_draft_computer_rooms.sql','utf8')
const cpu=readFileSync('supabase/migrations/20261022131000_draft_cpu_turns_and_lineups.sql','utf8')
const ui=readFileSync('components/DraftRoom.js','utf8')
const archive=readFileSync('components/DraftArchives.js','utf8')
const css=readFileSync('components/DraftRoom.module.css','utf8')

test('old draft rooms stay friends by default; bot rooms are distinct and private',()=>{
 assert.match(rooms,/opponent_mode text not null default 'friends'/)
 assert.match(rooms,/check\(opponent_mode in \('friends','computer'\)\)/)
 assert.match(rooms,/is_bot boolean not null default false/)
 assert.match(rooms,/check\(not is_bot or user_id is null\)/)
 assert.match(rooms,/scout_draft_create_vs_bot\(/)
 assert.match(rooms,/p_team_count not between 2 and 8/)
 assert.match(rooms,/room_data:=public\.scout_draft_create\(team_names,p_mode\)/)
 assert.match(rooms,/update public\.scout_draft_teams set is_bot=true/)
 assert.match(rooms,/if rm\.opponent_mode='computer' then raise exception 'BOT_ROOM_PRIVATE'/)
 assert.match(rooms,/if v_room\.opponent_mode='computer' then raise exception 'BOT_ROOM_PRIVATE'/)
 assert.match(rooms,/rm\.opponent_mode='computer' and rm\.host_user_id is distinct from auth\.uid\(\)/)
 assert.match(rooms,/user_id is not null or is_bot/)
 assert.match(rooms,/'is_bot',t\.is_bot/)
 assert.match(rooms,/'opponent_mode',rm\.opponent_mode/)
 assert.match(rooms,/t\.user_id=auth\.uid\(\)/)
})
test('bot advances are authorized room-locked actions and do not affect friends games',()=>{
 assert.match(cpu,/select \* into rm from public\.scout_draft_rooms where id=p_room_id for update/)
 assert.match(cpu,/rm\.opponent_mode<>'computer'/)
 assert.match(cpu,/where room_id=rm\.id and user_id=auth\.uid\(\) and is_bot=false/)
 assert.match(cpu,/if rm\.status<>'drafting'/)
 assert.match(cpu,/rm\.last_bot_action_at\+interval '1 second'/)
 assert.match(cpu,/auth\.uid\(\) is null/)
 assert.match(cpu,/grant execute on function public\.scout_draft_bot_advance\(uuid\) to authenticated/)
 assert.match(cpu,/revoke all on function public\.scout_draft_bot_advance\(uuid\) from public,anon/)
})
test('CPU Snake and Normal picks use frozen model, valid position slots and unique players',()=>{
 assert.match(cpu,/if rm\.draft_kind='classic'/)
 assert.match(cpu,/rm\.mode='snake' and mod\(v_round,2\)=0/)
 assert.match(cpu,/and is_bot=true/)
 assert.match(cpu,/pr\.run_id=rm\.model_run_id/)
 assert.match(cpu,/sp\.position in \('GK','DEF','MID','FWD'\)/)
 assert.match(cpu,/not exists\(select 1 from public\.scout_draft_picks p/)
 assert.match(cpu,/owned\.position=sp\.position/)
 assert.match(cpu,/coalesce\(pr\.xi_probability,0\)/)
 assert.match(cpu,/auto_selected\)/)
 assert.match(cpu,/status=case when rm\.next_pick=rm\.team_count\*15 then 'finished' else 'drafting' end/)
})
test('CPU auction uses legal bids, increment and reserved roster budget',()=>{
 assert.match(cpu,/rm\.auction_phase='completion'/)
 assert.match(cpu,/rm\.auction_nomination_index/)
 assert.match(cpu,/scout_draft_auction_lots/)
 assert.match(cpu,/scout_draft_auction_bids/)
 assert.match(cpu,/v_bid:=lot\.current_bid\+1/)
 assert.match(cpu,/rm\.auction_budget-count_all\.spent-\(14-count_all\.total\)/)
 assert.match(cpu,/rm\.auction_extension_seconds\*interval '1 second'/)
 assert.match(cpu,/rm\.auction_bid_seconds\*interval '1 second'/)
 assert.match(cpu,/and t\.id is distinct from lot\.leader_team_id/)
 assert.match(cpu,/clock_timestamp\(\)>=lot\.ends_at/)
 assert.match(cpu,/price,auto_selected/)
})
test('CPU teams get a legal ready 4-4-2 and bench when draft finishes',()=>{
 assert.match(cpu,/after update of status on public\.scout_draft_rooms/)
 assert.match(cpu,/new\.opponent_mode<>'computer' or not new\.lineup_required/)
 assert.match(cpu,/rank_pos<=case position when 'GK' then 1 when 'DEF' then 4/)
 assert.match(cpu,/not \(p\.player_id=any\(start_ids\)\)/)
 assert.match(cpu,/cardinality\(start_ids\)<>11 or cardinality\(bench_ids\)<>4/)
 assert.match(cpu,/where sp\.position<>'GK'/)
 assert.match(cpu,/values\(new\.id,bot\.id,new\.gameweek,'4-4-2',captain,'none',start_ids,bench_ids,true\)/)
 assert.match(cpu,/on conflict\(room_id,team_id,gameweek\) do nothing/)
})
