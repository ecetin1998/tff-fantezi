import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const schema=readFileSync('supabase/migrations/20261022120000_draft_cpu_opponents_schema.sql','utf8')
const bots=readFileSync('supabase/migrations/20261022121000_draft_cpu_manager_picks_and_lineups.sql','utf8')
const weekly=readFileSync('supabase/migrations/20261022122000_draft_cpu_weekly_lineup_refresh.sql','utf8')
const ui=readFileSync('components/DraftRoom.js','utf8')
const css=readFileSync('components/DraftRoom.module.css','utf8')

test('vs CPU is opt-in; legacy multiplayer remains default and uses existing create flow',()=>{
 assert.match(schema,/opponent_mode text not null default 'friends'/)
 assert.match(schema,/bot_difficulty text not null default 'normal'/)
 assert.match(schema,/is_bot boolean not null default false/)
 assert.match(schema,/create or replace function public\.scout_draft_create_vs_cpu/)
 assert.match(schema,/p_team_count not between 2 and 8/)
 assert.match(schema,/p_mode not in \('snake','linear'\)/)
 assert.match(schema,/bot_difficulty in \('easy','normal','hard'\)/)
 assert.match(ui,/Arkadaşlara Karşı/)
 assert.match(ui,/Bilgisayara Karşı/)
 assert.match(ui,/scout_draft_create_vs_cpu/)
 assert.match(ui,/scout_draft_create'/)
 assert.match(ui,/Bilgisayar zorluğu/)
 assert.match(css,/\.opponentModes/)
})

test('bot rooms are owner-only and no participant can occupy a machine seat',()=>{
 assert.match(schema,/COMPUTER_ROOM_PRIVATE/g)
 assert.match(schema,/rm\.opponent_mode='computer' and p_mode='auction'/)
 assert.match(schema,/v_room\.opponent_mode='computer'/)
 assert.match(schema,/rm\.opponent_mode='computer'/)
 assert.match(schema,/'occupied',\(t\.user_id is not null or t\.is_bot\)/)
 assert.match(schema,/'is_bot',t\.is_bot/)
 assert.match(schema,/'opponent_mode',rm\.opponent_mode/)
 assert.match(schema,/user_id is not null or is_bot/)
 assert.match(schema,/revoke all on function public\.scout_draft_create_vs_cpu\(text,integer,text,text\) from public,anon/)
})
test('computer pick is server-authoritative, atomic and follows Snake/Normal order',()=>{
 assert.match(bots,/create or replace function public\.scout_draft_cpu_advance/)
 assert.match(bots,/auth\.uid\(\) is null/)
 assert.match(bots,/where id=p_room_id for update/)
 assert.match(bots,/user_id=auth\.uid\(\) and is_bot=false/)
 assert.match(bots,/rm\.opponent_mode<>'computer'/)
 assert.match(bots,/rm\.draft_kind<>'classic'/)
 assert.match(bots,/if not found or not team\.is_bot then exit/)
 assert.match(bots,/rm\.mode='snake' and mod\(round_num,2\)=0/)
 assert.match(bots,/team\.id,player,rm\.next_pick,true/)
 assert.match(bots,/pr\.run_id=p_run_id/)
 assert.match(bots,/not exists\(select 1 from public\.scout_draft_picks other/)
 assert.match(bots,/pr\.xi_probability/)
 assert.match(bots,/pr\.x_minutes/)
 assert.match(bots,/pr\.availability_probability/)
 assert.match(ui,/scout_draft_cpu_advance/)
 assert.match(ui,/document\.visibilityState==='hidden'/)
})
test('bots create and refresh valid weekly XI, GK bench and captain without human action',()=>{
 assert.match(bots,/create or replace function private\.scout_draft_prepare_cpu_lineups/)
 assert.match(bots,/create trigger scout_draft_cpu_lineups_finished/)
 assert.match(bots,/for tm in select \* from public\.scout_draft_teams/)
 assert.match(bots,/where room_id=rm\.id and is_bot/)
 assert.match(bots,/where season=\(select max\(season\) from public\.scout_game_rules\)/)
 assert.match(bots,/cardinality\(best\)<>11/)
 assert.match(bots,/cardinality\(bench\)<>4/)
 assert.match(bots,/and sp\.position<>'GK'/)
 assert.match(bots,/selected_card:='bench_boost'/)
 assert.match(bots,/selected_card:='quad_captain'/)
 assert.match(bots,/selected_card:='triple_captain'/)
 assert.match(bots,/on conflict\(room_id,team_id,gameweek\) do nothing/)
 assert.match(weekly,/private\.scout_draft_prepare_cpu_lineups\(rm\.id,chosen_week\)/)
 assert.doesNotMatch(bots,/delete from public\.scout_draft_picks/)
})
test('CPU rooms never expose an invite action or unsupported auction rules',()=>{
 assert.match(ui,/room\.opponent_mode!=='computer'&&\['lobby','drafting'\]/)
 assert.match(ui,/opponentMode==='friends'&&<option value="auction">/)
 assert.match(ui,/room\.opponent_mode!=='computer'&&<option value="auction">/)
 assert.match(ui,/t\.is_bot\?'BİLGİSAYAR'/)
 assert.match(ui,/room\.bot_difficulty/)
})
