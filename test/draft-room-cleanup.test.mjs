import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const sql=readFileSync('supabase/migrations/20261022003000_draft_archive_cleanup_and_expiry.sql','utf8')
const ui=readFileSync('components/DraftRoom.js','utf8')
const archive=readFileSync('components/DraftArchives.js','utf8')
const css=readFileSync('components/DraftArchives.module.css','utf8')

test('inactive unfinished rooms expire via a real 15-minute pg_cron job after 24h without a heartbeat',()=>{
 assert.match(sql,/check\(status in \('lobby','drafting','finished','cancelled','expired'\)\)/)
 assert.match(sql,/last_member_seen_at<clock_timestamp\(\)-interval '24 hours'/)
 assert.match(sql,/where status in \('lobby','drafting'\)/)
 assert.match(sql,/cron\.schedule\('scout-draft-expire-inactive','\*\/15 \* \* \* \*'/)
 assert.match(sql,/create or replace function private\.scout_draft_expire_inactive\(\)/)
 assert.match(sql,/update public\.scout_draft_rooms set last_member_seen_at=greatest\(created_at,updated_at\)/)
 assert.doesNotMatch(sql,/delete from public\.scout_draft_rooms/)
})

test('authenticated member heartbeats do not revive expired or cancelled rooms',()=>{
 assert.match(sql,/create or replace function public\.scout_draft_heartbeat\(p_room_id uuid\)/)
 assert.match(sql,/where room_id=p_room_id and user_id=auth\.uid\(\)/)
 assert.match(sql,/rm\.last_member_seen_at<t-interval '24 hours'/)
 assert.match(sql,/update public\.scout_draft_rooms set status='expired'/)
 assert.match(sql,/if rm\.status not in \('lobby','drafting'\)/)
 assert.match(sql,/rm\.last_member_seen_at<t-interval '45 seconds'/)
 assert.match(ui,/scout_draft_heartbeat/)
 assert.match(ui,/document\.visibilityState==='hidden'/)
 assert.match(ui,/setInterval\(\(\)=>\{void heartbeat\(\)\},60000\)/)
})
test('host may soft cancel only unfinished drafts and finished leagues remain intact',()=>{
 assert.match(sql,/create or replace function public\.scout_draft_cancel_room\(p_room_id uuid\)/)
 assert.match(sql,/rm\.host_user_id is distinct from auth\.uid\(\)/)
 assert.match(sql,/if rm\.status='finished' then raise exception 'FINISHED_ROOM_PROTECTED'/)
 assert.match(sql,/set status='cancelled'/)
 assert.match(archive,/window\.confirm\(/)
 assert.match(archive,/Odayı iptal et/)
 assert.match(ui,/scout_draft_cancel_room/)
 assert.match(ui,/room\.is_host&&\['lobby','drafting'\]/)
})
test('user-only reversible archive hiding with RLS and membership enforcement',()=>{
 assert.match(sql,/create table if not exists public\.scout_draft_hidden_rooms/)
 assert.match(sql,/enable row level security/)
 assert.match(sql,/revoke all on public\.scout_draft_hidden_rooms from public,anon,authenticated/)
 assert.match(sql,/create or replace function public\.scout_draft_hide_room\(p_room_id uuid,p_hidden boolean default true\)/)
 assert.match(sql,/on conflict\(user_id,room_id\) do nothing/)
 assert.match(sql,/delete from public\.scout_draft_hidden_rooms/)
 assert.match(sql,/not exists\(select 1 from public\.scout_draft_hidden_rooms h/)
 assert.match(sql,/scout_draft_my_hidden_rooms\(\)/)
 assert.match(sql,/grant execute on function public\.scout_draft_hide_room\(uuid,boolean\) to authenticated/)
 assert.match(archive,/Gizlenenleri göster/)
 assert.match(archive,/Listemden kaldır/)
 assert.match(archive,/Geri getir/)
})
