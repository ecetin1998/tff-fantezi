import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const sql=readFileSync('supabase/migrations/20261022140000_draft_single_week_locked_league.sql','utf8')
const room=readFileSync('components/DraftRoom.js','utf8')
const editor=readFileSync('components/DraftLineupSetup.js','utf8')
const finalXI=readFileSync('components/DraftLeagueLineups.js','utf8')
const live=readFileSync('components/DraftLiveStandings.js','utf8')
const css=readFileSync('components/DraftLeagueLineups.module.css','utf8')

test('new rooms compete on frozen matchweek but existing finished draft results are unchanged',()=>{
 assert.match(sql,/single_week_only boolean not null default true/)
 assert.match(sql,/update public\.scout_draft_rooms set single_week_only=false/)
 assert.match(sql,/if rm\.single_week_only then max_week:=rm\.gameweek/)
 assert.match(sql,/max_week:=least\(max_week,34\)/)
 assert.match(sql,/pts\.gameweek between rm\.gameweek and max_week/)
 assert.match(sql,/'single_week_only',rm\.single_week_only/)
 assert.doesNotMatch(sql,/delete from public\.scout_draft_rooms|update public\.scout_player_weekly_points/)
})
test('new room UI tracks confirmed/remaining managers and masks private XI until all have saved',()=>{
 assert.match(sql,/'ready',coalesce\(l\.ready,false\)/)
 assert.match(sql,/'is_bot',t\.is_bot/)
 assert.match(sql,/'starters',case when rm\.league_active_at is not null then l\.starters else null end/)
 assert.match(sql,/'bench',case when rm\.league_active_at is not null then l\.bench else null end/)
 assert.match(sql,/'captain',case when rm\.league_active_at is not null then l\.captain_player_id else null end/)
 assert.match(sql,/'card',case when rm\.league_active_at is not null then l\.manager_card else null end/)
 assert.match(editor,/Kadro onay durumu/)
 assert.match(editor,/Kaydetmesi bekleniyor/)
 assert.match(editor,/Hazır/)
 assert.match(editor,/Kadroyu Kaydet ve Hazırım/)
 assert.match(editor,/Hazırım ✓/)
})
test('after all ready, saving another XI is forbidden on server, not just browser',()=>{
 assert.match(sql,/rm\.single_week_only and rm\.league_active_at is not null then raise exception 'LEAGUE_LINEUPS_LOCKED'/)
 assert.match(sql,/and \(not rm\.single_week_only or rm\.league_active_at is null\)/)
 assert.match(sql,/if rm\.single_week_only then[\s\S]*?current_week:=rm\.gameweek/)
 assert.match(sql,/select \* into rm from public\.scout_draft_rooms where id=p_room_id for update/)
 assert.match(sql,/count\(\*\)=count\(\*\) filter\(where l\.ready is true\)/)
})
test('live final page shows only confirmed squads and standings, never draft pool or previous boards',()=>{
 assert.match(room,/const rosterPhase=room\?\.status==='finished'&&Boolean\(room\?\.lineup_required\)/)
 assert.match(room,/const leagueReady=Boolean\(rosterPhase&&\(leagueActive\|\|room\?\.league_active_at\)\)/)
 assert.match(room,/\{rosterPhase&&\(!leagueReady/)
 assert.match(room,/<DraftLineupSetup/)
 assert.match(room,/<DraftLeagueLineups roomId=\{id\} picks=\{picked\}\/>/)
 assert.match(room,/<DraftLiveStandings roomId=\{id\}\/>/)
 assert.match(room,/\{!rosterPhase&&<>/)
 assert.match(room,/<div className=\{s\.board\}>/)
 assert.match(room,/<div className=\{s\.history\}>/)
 assert.match(finalXI,/scout_draft_lineup_state/)
 assert.match(finalXI,/KESİNLEŞEN KADROLAR/)
 assert.match(finalXI,/KAPTAN/)
 assert.match(finalXI,/Yedekler/)
 assert.match(finalXI,/cards\[focused\.card\]/)
 assert.match(css,/\.pitch/)
 assert.match(css,/\.teamActive/)
})
