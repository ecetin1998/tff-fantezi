import test from "node:test"
import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8")
test("team goals and advanced stats use independently sourced periods",()=>{
  const s=read("app/teams/[id]/page.js")
  assert.match(s,/advancedMatches>0\?Number\(s\?\.shots\|\|0\)\/advancedMatches/)
  assert.match(s,/advancedMatches>0\?Number\(s\?\.opponent_sot\|\|0\)\/advancedMatches/)
  assert.match(s,/const hasAlignedGoals=advancedMatches>0&&advancedMatches===matchesPlayed/)
  assert.match(s,/finishingDelta===null\?'—'/)
  assert.match(s,/defensiveDelta===null\?'—'/)
  assert.match(s,/MH1–MH\{advancedWeek\}/)
  assert.doesNotMatch(s,/Number\(s\?\.shots\|\|0\)\/safeMatches/)
  assert.doesNotMatch(s,/Number\(s\?\.goals_for\|\|0\)-Number\(s\?\.xg_total\|\|0\)(?!:null)/)
})
test("player card labels last verified advanced week and does not count DNP as an advanced zero",()=>{
  const s=read("app/players/[id]/page.js")
  assert.match(s,/seasonWeek>advancedWeek/)
  assert.match(s,/advancedNote/)
  assert.match(s,/DNP bağımsız doğrulanmalı/)
  assert.match(s,/advancedStale\?/)
  assert.doesNotMatch(s,/advanced_through_gameweek:\s*seasonWeek/)
})
test("legacy model snapshots remain untouched by UI-only coverage changes",()=>{
  const t=read("app/teams/[id]/page.js"),p=read("app/players/[id]/page.js")
  assert.doesNotMatch(t,/update\(|upsert\(|delete\(/)
  assert.doesNotMatch(p,/update\(|upsert\(|delete\(/)
})

test("MH11 reconciliation keeps unknowns and source timestamps honest",()=>{
  const sql=read("supabase/migrations/20261115200000_mh11_verified_advanced_coverage.sql")
  assert.match(sql,/s\.shots=t\.shots and s\.sot=t\.shots_on_target/)
  assert.match(sql,/w\.is_final and w\.minutes>0/)
  assert.match(sql,/a\.shots is null and a\.shots_on_target is null and a\.xg is null/)
  assert.match(sql,/else a\.xg end as xg,a\.xa/)
  assert.match(sql,/greatest\(a\.observed_at,e\.source_observed_at\)/)
  assert.match(sql,/revoke all on public\.scout_verified_weekly_attack_reconciled from public,anon,authenticated/)
  assert.doesNotMatch(sql,/update public\.scout_verified_weekly_attack\s/)
  assert.match(sql,/aggregate_through_gameweek=11/)
  assert.doesNotMatch(sql,/advanced_profile_through_gameweek\s*=/)
  const rpc=read("supabase/migrations/20261115200100_mh11_pro_player_reconciled_attack.sql")
  assert.match(rpc,/from public\.scout_verified_weekly_attack_reconciled a/)
  assert.match(rpc,/s\.plan='pro'/)
  assert.match(rpc,/errcode='42501'/)
  const worker=read("supabase/functions/weekly-model-lifecycle/recentAttackForm.mjs")
  assert.match(worker,/scout_verified_weekly_attack_reconciled/)
  const team=read("app/teams/[id]/page.js")
  assert.match(team,/aggregate_through_gameweek/)
  assert.match(team,/Ayrıntılı olay MH/)
})
