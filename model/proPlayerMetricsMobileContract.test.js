const assert=require('node:assert/strict')
const fs=require('node:fs')
const read=p=>fs.readFileSync(p,'utf8')

const players=read('components/PlayersTable.js')
const proRoute=read('app/api/pro-player-overlay/route.js')
const data=read('lib/data.js')
const styles=read('components/DataViews.module.css')
const teams=read('components/TeamsExplorer.js')

assert.match(players,/const proMetricsPending=isPro&&!overlayReady/)
assert.match(players,/disabled=\{proMetricsPending\}/,'Do not let mobile Pro P90/6+ sort silently read empty metrics')
assert.match(players,/aria-busy=\{proMetricsPending/,'Explain asynchronous private sorting state')
assert.match(players,/isPro&&isAdvancedSort\(key\)&&!overlayReady\)return/,'Disable advanced table sort until private overlay arrives')
assert.match(players,/isPro&&isAdvancedSort\(f\.sort\)&&!overlayReady\?'xfp'/,'While loading, retain meaningful xFP order rather than sorting nulls as 0')
assert.match(players,/an=av===null\|\|av===undefined/,'Missing advanced metrics must not be treated as genuine zero')
assert.match(players,/overlayReady\?pct\(p\.projection\?\.six_plus_probability\)/,'Show 6+ only after authorized data loaded')
assert.match(players,/overlayReady\?num\(p\.projection\?\.p90,1\)/,'Show P90 only after authorized data loaded')
assert.match(players,/overlayError\?'—':'…'/,'An in-progress value should not display as 0% or a permanent dash')
assert.match(players,/p90:extra\.p90,six_plus_probability:extra\.six_plus_probability/,'Current Pro RPC fields merge into cards before sorting')
assert.match(players,/if\(response\.status===409\)/,'Cached model mismatch is not silently treated as missing data')
assert.match(players,/if\(players\.length&&matched\/players\.length<\.95\)/,'Pro overlay coverage is verified')
assert.match(proRoute,/auth\.plan!=='pro'/,'Private metrics must require Pro')
assert.match(proRoute,/requestedRun&&requestedRun!==run\.id/,'A prior-week overlay cannot be used for current-week sorting')
assert.match(proRoute,/Cache-Control':'private, no-store'/)
assert.match(data,/supabase\.rpc\('scout_pro_player_overlay'/,'Fetch private projection metrics through authorized RPC')
assert.match(data,/p25:null,p75:null,p90:null,six_plus_probability:null/,'Public player list remains free of Pro-only values')

assert.match(teams,/className="card team-analysis-mobile-card team-accent-card"/,'Team mobile card selector exists')
assert.match(styles,/\.scope :global\(\.team-analysis-card-list\)\{[\s\S]*?grid-template-columns:minmax\(0,1fr\)/,'Long fixtures must not widen the entire team grid')
assert.match(styles,/\.scope :global\(\.team-analysis-mobile-card\)\{[\s\S]*?overflow:hidden/,'Cards clip decorative overflow on narrow screens')
assert.match(styles,/\.scope :global\(\.team-analysis-mobile-card\) :global\(\.fixture-strength-strip\)\{[\s\S]*?overflow-x:auto/,'Five-week strip scrolls within the mobile card')
assert.match(styles,/\.scope :global\(\.team-analysis-mobile-head\)\{[\s\S]*?grid-template-columns:42px minmax\(0,1fr\) max-content/,'Mobile team name shrinks without clipping xFP')

console.log('Pro player metrics and mobile team card guards passed')
