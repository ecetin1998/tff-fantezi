import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const schema=readFileSync('supabase/migrations/20261021220000_draft_lineup_foundation.sql','utf8')
const scoring=readFileSync('supabase/migrations/20261021221500_draft_lineup_verified_scoring.sql','utf8')
const editor=readFileSync('components/DraftLineupSetup.js','utf8')
const room=readFileSync('components/DraftRoom.js','utf8')
const board=readFileSync('components/DraftLiveStandings.js','utf8')

test('new lineup storage preserves older draft rooms and gates a live league behind all-ready',()=>{
 assert.match(schema,/add column if not exists lineup_required boolean not null default true/)
 assert.match(schema,/update public\.scout_draft_rooms set lineup_required=false/)
 assert.match(schema,/league_active_at/)
 assert.match(schema,/rm\.status<>'finished'/)
 assert.match(schema,/count\(\*\)=count\(\*\) filter\(where l\.ready is true\)/)
 assert.match(schema,/update public\.scout_draft_rooms set league_active_at=clock_timestamp\(\)/)
 assert.match(room,/rosterPhase&&\(!leagueReady/)
 assert.match(room,/leagueActive\|\|room\?\.league_active_at/)
})
test('lineup saving enforces authenticated ownership, original drafted roster, GK bench and captain',()=>{
 assert.match(schema,/if auth\.uid\(\) is null then raise exception 'AUTH_REQUIRED'/)
 assert.match(schema,/from public\.scout_draft_teams where room_id=rm\.id and user_id=auth\.uid\(\)/)
 assert.match(schema,/cardinality\(p_starters\)<>11 or cardinality\(p_bench\)<>4/)
 assert.match(schema,/count\(distinct x\) from unnest\(all_ids\)/)
 assert.match(schema,/player_id=any\(all_ids\)/)
 assert.match(schema,/p_captain=any\(p_starters\)/)
 assert.match(schema,/p_bench\[1\] and position='GK'/)
 assert.match(schema,/jsonb_array_elements_text\(g\.rules->'formations'\)/)
 assert.match(schema,/clock_timestamp\(\)>=deadline/)
 assert.match(schema,/revoke all on table public\.scout_draft_lineups from anon,authenticated/)
 assert.match(schema,/revoke all on function public\.scout_draft_save_lineup.*from public,anon/)
})
test('manager cards are explicit, single-use and unworkable draft-specific options are disabled',()=>{
 assert.match(schema,/where manager_card<>'none'/)
 assert.match(schema,/CARD_ALREADY_USED/)
 assert.match(schema,/triple_captain/)
 assert.match(schema,/quad_captain/)
 assert.match(schema,/bench_boost/)
 assert.match(editor,/Hücum kartının 2 KL \/ 3 DEF \/ 5 OS \/ 5 FOR kadrosu/)
 assert.match(editor,/Limitsiz Bütçe/)
 assert.match(editor,/Kaptan/)
})
test('verified weekly scoring uses XI, multiplier, bench boost and safe same-position autosubs',()=>{
 assert.match(scoring,/rm\.lineup_required and rm\.league_active_at is null/)
 assert.match(scoring,/pts\.is_final is true/)
 assert.match(scoring,/fantasy_closure='KAPANDI'/)
 assert.match(scoring,/left join lateral/)
 assert.match(scoring,/line\.gameweek<=v\.gameweek/)
 assert.match(scoring,/line\.ready is true/)
 assert.match(scoring,/case when l\.gameweek=v\.gameweek then l\.manager_card else 'none' end/)
 assert.match(scoring,/v\.player_id=any\(v\.starters\)/)
 assert.match(scoring,/v\.card='bench_boost'/)
 assert.match(scoring,/when 'triple_captain' then 2/)
 assert.match(scoring,/when 'quad_captain' then 3/)
 assert.match(scoring,/a\.position=b\.position/)
 assert.match(scoring,/v\.minutes,?/i)
 assert.match(scoring,/sum\(scored_points\)/)
 assert.match(scoring,/lineup_xi_captain_cards/)
 assert.match(scoring,/not rm\.lineup_required then v\.points/)
 assert.doesNotMatch(scoring,/\binsert into public\.scout_player_weekly_points\b|\bupdate public\.scout_player_weekly_points\b/)
})
test('frontend guards old archives, pending scores, XI selection and save readiness',()=>{
 assert.match(editor,/scout_draft_lineup_state/)
 assert.match(editor,/scout_draft_save_lineup/)
 assert.match(editor,/Kadroyu Kaydet ve Hazırım/)
 assert.match(editor,/role="status"/)
 assert.match(editor,/disabled=\{locked\}/)
 assert.match(editor,/FORMATION_MAP/)
 assert.match(board,/counted_points/)
 assert.match(board,/is_starter/)
 assert.match(board,/auto_sub/)
 assert.match(room,/DraftLiveStandings/)
})
